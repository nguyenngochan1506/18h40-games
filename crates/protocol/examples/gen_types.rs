use protocol::{
    ClientMessage, ErrorCode, GameAction, GameDelta, GameKind, GameSeat, GameSettings,
    GameSnapshot, GameView, Member, PROTOCOL_VERSION, Phase, Role, RoomView, ServerMessage,
    VoiceError, VoiceTokenResult,
};
use std::{fs, path::Path};
use ts_rs::TS;

fn main() -> std::io::Result<()> {
    let config = ts_rs::Config::default();
    let output =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../../apps/web/src/generated/protocol.ts");
    fs::create_dir_all(output.parent().unwrap())?;
    let declarations = [
        bang::GameMode::decl(&config),
        bang::RoleCounts::decl(&config),
        bang::GameConfig::decl(&config),
        bang::PlayerId::decl(&config),
        bang::CardId::decl(&config),
        bang::CardKind::decl(&config),
        bang::Role::decl(&config),
        bang::Character::decl(&config),
        bang::CardSelection::decl(&config),
        bang::DrawSource::decl(&config),
        bang::Action::decl(&config),
        bang::TurnStep::decl(&config),
        bang::TurnState::decl(&config),
        bang::PendingId::decl(&config),
        bang::AttackKind::decl(&config),
        bang::Winner::decl(&config),
        bang::DecisionKind::decl(&config),
        bang::Decision::decl(&config),
        bang::view::PublicPlayer::decl(&config),
        bang::SpectatorView::decl(&config),
        bang::PlayerView::decl(&config),
        bang::EventKind::decl(&config),
        uno::Settings::decl(&config),
        uno::Action::decl(&config),
        uno::View::decl(&config),
        uno::Events::decl(&config),
        werewolf::Settings::decl(&config),
        werewolf::Action::decl(&config),
        werewolf::View::decl(&config),
        werewolf::Events::decl(&config),
        ::cats::Settings::decl(&config),
        ::cats::PlayerId::decl(&config),
        ::cats::CardId::decl(&config),
        ::cats::CardKind::decl(&config),
        ::cats::CardView::decl(&config),
        ::cats::Action::decl(&config),
        ::cats::TurnState::decl(&config),
        ::cats::PendingId::decl(&config),
        ::cats::DecisionKind::decl(&config),
        ::cats::Decision::decl(&config),
        ::cats::view::PublicPlayer::decl(&config),
        ::cats::SpectatorView::decl(&config),
        ::cats::PlayerView::decl(&config),
        ::cats::PlayedAction::decl(&config),
        ::cats::PublicAction::decl(&config),
        ::cats::EventKind::decl(&config),
        GameView::decl(&config),
        GameSeat::decl(&config),
        GameSnapshot::decl(&config),
        protocol::bang::BangEvents::decl(&config),
        protocol::bang::BangView::decl(&config),
        protocol::cats::CatsEvents::decl(&config),
        protocol::cats::CatsView::decl(&config),
        GameSettings::decl(&config),
        GameAction::decl(&config),
        GameDelta::decl(&config),
        ErrorCode::decl(&config),
        Phase::decl(&config),
        Role::decl(&config),
        Member::decl(&config),
        GameKind::decl(&config),
        RoomView::decl(&config),
        VoiceError::decl(&config),
        VoiceTokenResult::decl(&config),
        ClientMessage::decl(&config),
        ServerMessage::decl(&config),
    ];
    let mut source = format!(
        "// Generated by scripts/gen-types.sh. Do not edit.\n\nexport const PROTOCOL_VERSION = {PROTOCOL_VERSION};\n"
    );
    for declaration in declarations {
        source.push_str(&format!("\nexport {declaration}\n"));
    }
    fs::write(
        output,
        source
            .lines()
            .map(str::trim_end)
            .collect::<Vec<_>>()
            .join("\n")
            + "\n",
    )
}
